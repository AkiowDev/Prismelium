-- =====================================================================

DROP DATABASE IF EXISTS Prismelium;
CREATE DATABASE Prismelium;
USE Prismelium;

CREATE TABLE RESSOURCE(
    Id_Res INT AUTO_INCREMENT,
    Nom_Res VARCHAR(50) NOT NULL,
    Dispo_Res BOOLEAN NOT NULL DEFAULT TRUE,
    Type_Res VARCHAR(50) NOT NULL,
    Poids_Res DECIMAL(10,2),
    Stockage_Res VARCHAR(50),
    PRIMARY KEY(Id_Res)
);

CREATE TABLE ROLE(
    Id_Role INT AUTO_INCREMENT,
    Nom_Role VARCHAR(50) NOT NULL UNIQUE,
    PRIMARY KEY(Id_Role)
);

CREATE TABLE EQUIPE(
    Id_Equipe INT AUTO_INCREMENT,
    Nom_Equipe VARCHAR(50) NOT NULL,
    PRIMARY KEY(Id_Equipe)
);

CREATE TABLE PERMISSION(
    Id_Perm INT AUTO_INCREMENT,
    Nom_Perm VARCHAR(50) NOT NULL,
    Desc_Perm VARCHAR(255) NOT NULL,
    PRIMARY KEY(Id_Perm)
);

CREATE TABLE CONTRAINTE(
    Id_Contrainte INT AUTO_INCREMENT,
    Nom_Contrainte VARCHAR(50) NOT NULL UNIQUE,
    Desc_Contrainte VARCHAR(500),
    PRIMARY KEY(Id_Contrainte)
);

CREATE TABLE UTILISATEUR(
    Id_User INT AUTO_INCREMENT,
    Nom_User VARCHAR(50) NOT NULL,
    Prenom_User VARCHAR(50) NOT NULL,
    Birth_User DATE NOT NULL,
    Mail_User VARCHAR(100) NOT NULL UNIQUE,
    Mdp_User VARCHAR(255) NOT NULL,
    Tel_User VARCHAR(20),
    Desc_User VARCHAR(500),
    Genre_User VARCHAR(20) NOT NULL,
    Lang_User VARCHAR(10) NOT NULL DEFAULT 'FR',
    Mode_User VARCHAR(10) NOT NULL DEFAULT 'Clair',
    Date_Insc DATE NOT NULL DEFAULT (CURRENT_DATE),
    Rgpd_User BOOLEAN NOT NULL DEFAULT FALSE,
    Id_Equipe INT,
    Id_Role INT NOT NULL,
    PRIMARY KEY(Id_User),
    FOREIGN KEY(Id_Equipe) REFERENCES EQUIPE(Id_Equipe),
    FOREIGN KEY(Id_Role) REFERENCES ROLE(Id_Role)
);

CREATE TABLE EXPERIMENTATION(
    Id_Exp INT AUTO_INCREMENT,
    Nom_Exp VARCHAR(100) NOT NULL,
    Desc_Exp VARCHAR(1000),
    Date_Debut_Exp DATETIME NOT NULL,
    Date_Fin_Exp DATETIME NOT NULL,
    Statut_Exp VARCHAR(20) NOT NULL DEFAULT 'Brouillon',
    Type_Retribution VARCHAR(50),
    Montant_Retribution DECIMAL(10,2),
    Duree_Exp_Min INT UNSIGNED,
    Nb_Sessions_Prevues INT UNSIGNED, 
    Id_Equipe INT NOT NULL,
    PRIMARY KEY(Id_Exp),
    FOREIGN KEY(Id_Equipe) REFERENCES EQUIPE(Id_Equipe)
);

CREATE TABLE LIVRABLE(
    Id_Liv INT AUTO_INCREMENT,
    Nom_Liv VARCHAR(100) NOT NULL,
    Date_Liv DATE NOT NULL DEFAULT (CURRENT_DATE),
    Type_Liv VARCHAR(50) NOT NULL,
    Id_Exp INT NOT NULL,
    Id_User INT NOT NULL,
    PRIMARY KEY(Id_Liv),
    FOREIGN KEY(Id_Exp) REFERENCES EXPERIMENTATION(Id_Exp),
    FOREIGN KEY(Id_User) REFERENCES UTILISATEUR(Id_User)
);

CREATE TABLE SESSION(
    Id_Ses INT AUTO_INCREMENT,
    Date_Ses DATE NOT NULL,
    Debut_Ses TIME NOT NULL,
    Fin_Ses TIME NOT NULL,
    Statut_Ses VARCHAR(20) NOT NULL DEFAULT 'En attente',
    Nb_Place_Max INT NOT NULL,
    Id_Exp INT NOT NULL,
    PRIMARY KEY(Id_Ses),
    FOREIGN KEY(Id_Exp) REFERENCES EXPERIMENTATION(Id_Exp),
    CONSTRAINT CHK_Nb_Place_Max CHECK (Nb_Place_Max > 0)
);

CREATE TABLE QUESTIONNAIRE(
    Id_Quest INT AUTO_INCREMENT,
    Nom_Quest VARCHAR(100) NOT NULL,
    Ano_Quest BOOLEAN NOT NULL DEFAULT FALSE,
    Id_Exp INT NOT NULL,
    PRIMARY KEY(Id_Quest),
    FOREIGN KEY(Id_Exp) REFERENCES EXPERIMENTATION(Id_Exp)
);

CREATE TABLE QUESTION(
    Id_Question INT AUTO_INCREMENT,
    Contenu_Question VARCHAR(500) NOT NULL,
    Id_Quest INT NOT NULL,
    PRIMARY KEY(Id_Question),
    FOREIGN KEY(Id_Quest) REFERENCES QUESTIONNAIRE(Id_Quest)
);

CREATE TABLE REPONSE(
    Id_User INT NOT NULL,
    Id_Question INT NOT NULL,
    Contenu_Rep VARCHAR(500) NOT NULL,
    PRIMARY KEY(Id_User, Id_Question),
    FOREIGN KEY(Id_User) REFERENCES UTILISATEUR(Id_User),
    FOREIGN KEY(Id_Question) REFERENCES QUESTION(Id_Question)
);

CREATE TABLE DOCUMENT(
    Id_Doc INT AUTO_INCREMENT,
    Nom_Doc VARCHAR(100) NOT NULL,
    Type_Doc VARCHAR(50) NOT NULL,
    Poids_Doc INT NOT NULL,
    Url_Doc VARCHAR(500) NOT NULL,
    Id_Exp INT,
    PRIMARY KEY(Id_Doc),
    FOREIGN KEY(Id_Exp) REFERENCES EXPERIMENTATION(Id_Exp)
);

CREATE TABLE JOURNAL_LOG(
    Id_Log INT AUTO_INCREMENT,
    Type_Log VARCHAR(50) NOT NULL,
    Date_Log DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    IP_log VARCHAR(45) NOT NULL,
    Erreur_Log VARCHAR(255),
    Id_User INT NOT NULL,
    PRIMARY KEY(Id_Log),
    FOREIGN KEY(Id_User) REFERENCES UTILISATEUR(Id_User)
);

CREATE TABLE ADMINISTRATION(
    Id_Role INT NOT NULL,
    Id_Perm INT NOT NULL,
    PRIMARY KEY(Id_Role, Id_Perm),
    FOREIGN KEY(Id_Role) REFERENCES ROLE(Id_Role),
    FOREIGN KEY(Id_Perm) REFERENCES PERMISSION(Id_Perm)
);

CREATE TABLE RESTRICTION(
    Id_User INT NOT NULL,
    Id_Contrainte INT NOT NULL,
    PRIMARY KEY(Id_User, Id_Contrainte),
    FOREIGN KEY(Id_User) REFERENCES UTILISATEUR(Id_User),
    FOREIGN KEY(Id_Contrainte) REFERENCES CONTRAINTE(Id_Contrainte)
);

CREATE TABLE MESSAGERIE(
    Id_Msg INT AUTO_INCREMENT,
    Id_Expediteur INT NOT NULL,
    Id_Destinataire INT NOT NULL,
    Date_Msg DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    Contenu_Msg VARCHAR(1000) NOT NULL,
    Statut_Msg VARCHAR(20) NOT NULL DEFAULT 'envoyé',
    lu_Msg BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY(Id_Msg),
    FOREIGN KEY(Id_Expediteur) REFERENCES UTILISATEUR(Id_User),
    FOREIGN KEY(Id_Destinataire) REFERENCES UTILISATEUR(Id_User)
);

CREATE TABLE INSCRIPTION(
    Id_User INT NOT NULL,
    Id_Ses INT NOT NULL,
    Statut_Insc VARCHAR(20) NOT NULL DEFAULT 'En attente',
    Date_Demande DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    Retrib_Valid BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY(Id_User, Id_Ses),
    FOREIGN KEY(Id_User) REFERENCES UTILISATEUR(Id_User),
    FOREIGN KEY(Id_Ses) REFERENCES SESSION(Id_Ses)
);

CREATE TABLE LIMITES(
    Id_Exp INT NOT NULL,
    Id_Contrainte INT NOT NULL,
    Val_Min INT,
    Val_Max INT,
    PRIMARY KEY(Id_Exp, Id_Contrainte),
    FOREIGN KEY(Id_Exp) REFERENCES EXPERIMENTATION(Id_Exp),
    FOREIGN KEY(Id_Contrainte) REFERENCES CONTRAINTE(Id_Contrainte)
);

CREATE TABLE RESERVATION(
    Id_Res INT NOT NULL,
    Id_Ses INT NOT NULL,
    PRIMARY KEY(Id_Res, Id_Ses),
    FOREIGN KEY(Id_Res) REFERENCES RESSOURCE(Id_Res),
    FOREIGN KEY(Id_Ses) REFERENCES SESSION(Id_Ses)
);